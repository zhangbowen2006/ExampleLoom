import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {handle} from '../dist/engine.js';
const request=q=>JSON.parse(handle(JSON.stringify(q)));
const run=q=>{const r=request(q);assert.equal(r.ok,true,r.error);return r;};
const input={columns:['c0'],rows:[['A']]};
const examples=[{input,output:input}];
const report=run({op:'synthesize_table',examples});
const snapshot=JSON.stringify(report);
const result=run({op:'propose_table_input',pipelines:report.candidates.map(c=>c.pipeline),inputs:[input]});
assert.ok(result.suggestion);assert.ok(result.attempted<=8);
assert.ok(result.suggestion.groups.length>1);assert.ok(result.suggestion.score>0);
assert.equal(result.suggestion.source_index,0);assert.equal(result.suggestion.mutation,'duplicate_rows');
assert.deepEqual(result.suggestion.input,{columns:['c0'],rows:[['A'],['A']]});
assert.equal(Object.hasOwn(result.suggestion,'target'),false);
assert.equal(JSON.stringify(report),snapshot);
// A simulated user supplies the independent whole-table intention. No candidate
// prediction or external reference supplies this additional training target.
const probe=result.suggestion.input;
const expected={columns:probe.rows.flat().map((_,i)=>`c${i}`),rows:[probe.rows.flat()]};
const refined=run({op:'synthesize_table',examples:[...examples,{input:probe,output:expected}]});
const next={columns:['c0'],rows:[['X'],['Y'],['Z']]};
assert.deepEqual(run({op:'transform',pipeline:refined.candidates[0].pipeline,table:next}).table,{columns:['c0','c1','c2'],rows:[['X','Y','Z']]});
const identity={version:2,columns:['c0'],steps:[]};
assert.equal(run({op:'propose_table_input',pipelines:[identity,identity],inputs:[input]}).suggestion,null);
const fail={version:2,columns:['c0'],steps:[['split_column','c0',',',['a','b']]]};
assert.equal(run({op:'propose_table_input',pipelines:[fail,fail],inputs:[input]}).suggestion,null);
assert.equal(request({op:'propose_table_input',pipelines:[{...identity,steps:[['unknown']]}],inputs:[input]}).ok,false);
assert.equal(request({op:'propose_table_input',pipelines:[identity],inputs:[{columns:['c0'],rows:[]}]}).ok,false);
assert.equal(request({op:'propose_table_input',pipelines:[identity],inputs:[input],target:input}).ok,false);
const mixed=run({op:'propose_table_input',pipelines:[identity,fail],inputs:[input]});
assert.ok(mixed.suggestion,'An execution error is an explicit disagreement, never evidence of a correct label');
const larger={columns:['c0'],rows:Array.from({length:128},(_,i)=>[String(i)])};
assert.ok(run({op:'propose_table_input',pipelines:[identity,fail],inputs:[larger,larger]}).attempted<=8);
await mkdir('artifacts/probes',{recursive:true});
await writeFile('artifacts/probes/input.csv','c0\nA\n');await writeFile('artifacts/probes/report.json',JSON.stringify(report));
const cli=JSON.parse(execFileSync(process.execPath,['bin/exampleloom.mjs','probe-table','--data','artifacts/probes/input.csv','--report','artifacts/probes/report.json'],{encoding:'utf8'}));
assert.deepEqual(cli,result);
await writeFile('artifacts/table-probe-results.json',JSON.stringify({timestamp:new Date().toISOString(),engine_sha256:JSON.parse(await readFile('dist/BUILD.json','utf8')).engine_sha256,methodology:'Constructed input suggestion using only known inputs and retained candidates. An independent simulated user supplies the whole-table target. This is not an unassisted external benchmark.',suggestion:result,refined_candidates:refined.candidates.length,checks:['bounded input-only proposal','no ranking or label mutation','independent user refinement','unseen third batch','no all-failed suggestion','invalid declarations rejected','real CLI']},null,2)+'\n');
console.log('Bounded input proposal, independent refinement, unchanged ranking, failure handling and real CLI passed.');
