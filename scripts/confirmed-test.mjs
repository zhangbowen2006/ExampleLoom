import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {handle} from '../dist/engine.js';
const call=q=>JSON.parse(handle(JSON.stringify(q)));
const identity={version:2,columns:['c0'],steps:[]},flatten={version:2,columns:['c0'],steps:[['flatten_rows']]};
const table={columns:['c0'],rows:[['A'],['B']]};
const q={op:'execute_table',pipelines:[identity,flatten],table};
assert.equal(call(q).ok,false);
const explicit=call({...q,chosen:1});assert.equal(explicit.ok,true);assert.equal(explicit.selection,'explicit_choice');assert.equal(explicit.chosen,1);
const agreed=call({...q,pipelines:[identity,identity]});assert.equal(agreed.ok,true);assert.equal(agreed.selection,'observed_consensus');assert.equal(agreed.chosen,null);
assert.equal(call({...q,target:table}).ok,false);
const failure={version:2,columns:['missing'],steps:[]};
assert.equal(call({...q,pipelines:[identity,failure]}).ok,false);
assert.equal(call({...q,pipelines:[failure,failure]}).ok,false);
assert.equal(call({...q,chosen:-1}).ok,false);
const first=call({...q,table:{columns:['c0'],rows:[['A']]}});assert.equal(first.ok,true);
assert.equal(call(q).ok,false,'Consensus must be recomputed on the new complete batch');
await mkdir('artifacts/confirmed',{recursive:true});
await writeFile('artifacts/confirmed/input.csv','c0\nA\nB\n');
await writeFile('artifacts/confirmed/report.json',JSON.stringify({candidates:[identity,flatten].map(pipeline=>({pipeline}))}));
await writeFile('artifacts/confirmed/result.csv','existing output');
const cli=(...args)=>spawnSync(process.execPath,['bin/exampleloom.mjs','execute-table','--data','artifacts/confirmed/input.csv','--report','artifacts/confirmed/report.json','--out','artifacts/confirmed/result.csv',...args],{encoding:'utf8'});
assert.notEqual(cli().status,0);assert.equal(await readFile('artifacts/confirmed/result.csv','utf8'),'existing output','Failure must not overwrite the existing artifact');
const selected=cli('--choose','1');assert.equal(selected.status,0,selected.stderr);assert.match(selected.stderr,/explicit_choice/);
assert.equal(await readFile('artifacts/confirmed/result.csv','utf8'),explicit.csv);
await writeFile('artifacts/confirmed-results.json',JSON.stringify({timestamp:new Date().toISOString(),checks:['all retained programs on the complete batch','no error candidate dropped','independent new-batch check','strict no-target request','explicit zero-based choice','real CLI failure preserves prior artifact'],source:'Constructed checks, not a guarantee of unknown input correctness.'},null,2)+'\n');
console.log('Confirmed execution API/CLI agreement, failure and validation-failure artifact preservation checks passed.');
